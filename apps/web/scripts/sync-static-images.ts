/**
 * Copy the bundled photos (public/menu/**) to ImageKit, so the website resizes them
 * there instead of on Vercel (Vercel Hobby: 5K image transformations a month).
 *
 * The photos stay in git (public/menu) as the source of truth. This script only puts
 * a copy on an ImageKit account and writes src/lib/static-images.imagekit.json — the
 * map the image loader (src/lib/image-cdn.ts) uses. Each copy's name carries a hash of
 * its content, so a changed photo gets a new URL (no stale CDN cache).
 *
 * Safe by design: a photo added or changed without re-running this script is resized by
 * Vercel (next.config.ts compares each file with its copy's hash at build and warns),
 * and an ImageKit account never synced with the current set is not used at all.
 *
 * Usage:
 *   pnpm --filter web images:sync                       # DEV keys (.env.development.local)
 *   SEED_ENV=production pnpm --filter web images:sync   # LIVE keys (.env.production.local)
 *   pnpm --filter web images:sync --check               # no network: is the map up to date?
 *
 * Moving to another image CDN later: see the note at the top of src/lib/image-cdn.ts.
 */
import { createHash } from "crypto";
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from "fs";
import { config } from "dotenv";
import { extname, join, relative, resolve, sep } from "path";

const webRoot = resolve(__dirname, "..");
const PUBLIC_DIR = join(webRoot, "public");
/** Bundled photo folders (under public/) that go to ImageKit. */
const SOURCE_DIRS = ["menu"];
const IMAGE_EXT = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif"]);
/** Folder on ImageKit — separate from owner uploads (brovobites/menu/...). */
const IK_ROOT = "brovobites/static";
const IK_TAG = "brovobites-static";
const MANIFEST_PATH = join(webRoot, "src/lib/static-images.imagekit.json");

type Manifest = {
  _about: string;
  /** Hash of the whole photo set — an endpoint is used only when it matches. */
  version: string;
  /** "/menu/brovo/hero/hero-1.jpg" → "brovobites/static/menu/brovo/hero/hero-1.<hash>.jpg" */
  files: Record<string, string>;
  /** ImageKit URL endpoint → the `version` last synced to it. */
  endpoints: Record<string, string>;
};

const ABOUT =
  "Generated by apps/web/scripts/sync-static-images.ts — do not edit by hand. Maps bundled public/ photos to their copies on ImageKit (see src/lib/image-cdn.ts).";

function walk(dir: string): string[] {
  const out: string[] = [];
  for (const name of readdirSync(dir)) {
    if (name.startsWith(".")) continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else if (IMAGE_EXT.has(extname(name).toLowerCase())) out.push(full);
  }
  return out;
}

function sha(data: Buffer | string, len: number) {
  return createHash("sha256").update(data).digest("hex").slice(0, len);
}

type Photo = { publicPath: string; ikPath: string; abs: string };

function collect(): { photos: Photo[]; files: Record<string, string>; version: string } {
  const photos: Photo[] = [];
  for (const d of SOURCE_DIRS) {
    const root = join(PUBLIC_DIR, d);
    if (!existsSync(root)) continue;
    for (const abs of walk(root)) {
      const rel = relative(PUBLIC_DIR, abs).split(sep).join("/");
      const ext = extname(rel);
      const hash = sha(readFileSync(abs), 10);
      photos.push({
        publicPath: `/${rel}`,
        ikPath: `${IK_ROOT}/${rel.slice(0, -ext.length)}.${hash}${ext.toLowerCase()}`,
        abs,
      });
    }
  }
  photos.sort((a, b) => a.publicPath.localeCompare(b.publicPath));
  const files = Object.fromEntries(photos.map((p) => [p.publicPath, p.ikPath]));
  const version = sha(photos.map((p) => `${p.publicPath}:${p.ikPath}`).join("\n"), 12);
  return { photos, files, version };
}

function readManifest(): Manifest | null {
  if (!existsSync(MANIFEST_PATH)) return null;
  return JSON.parse(readFileSync(MANIFEST_PATH, "utf8")) as Manifest;
}

function check() {
  const { version, photos, files } = collect();
  const m = readManifest();
  const synced = Object.entries(m?.endpoints ?? {})
    .filter(([, v]) => v === version)
    .map(([e]) => e);
  if (!m || m.version !== version) {
    const changed = Object.keys(files).filter((p) => m?.files[p] !== files[p]);
    const removed = Object.keys(m?.files ?? {}).filter((p) => !(p in files));
    console.error(
      `✗ Bundled photos changed since the last sync — ImageKit copies are out of date:\n` +
        [...changed.map((p) => `    new/changed  ${p}`), ...removed.map((p) => `    removed      ${p}`)].join("\n") +
        "\n" +
        "  Run: pnpm --filter web images:sync  (and SEED_ENV=production … for LIVE)\n" +
        "  Until then the changed / new photos are resized by Vercel (still works).",
    );
    process.exit(1);
  }
  console.log(`✓ ${photos.length} bundled photos, map up to date (version ${version}).`);
  console.log(`  On ImageKit for: ${synced.length ? synced.join(", ") : "(no endpoint yet)"}`);
}

async function listExisting(auth: string): Promise<Set<string>> {
  const seen = new Set<string>();
  for (let skip = 0; ; skip += 1000) {
    // By tag: the `path` filter only lists one folder, not its subfolders.
    const q = new URLSearchParams({
      searchQuery: `tags IN ["${IK_TAG}"]`,
      type: "file",
      limit: "1000",
      skip: String(skip),
    });
    const res = await fetch(`https://api.imagekit.io/v1/files?${q}`, {
      headers: { Authorization: auth },
    });
    if (!res.ok) throw new Error(`ImageKit list failed (${res.status}): ${await res.text()}`);
    const page = (await res.json()) as { filePath: string }[];
    for (const f of page) seen.add(f.filePath.replace(/^\//, ""));
    if (page.length < 1000) return seen;
  }
}

async function upload(auth: string, publicKey: string, p: Photo) {
  const slash = p.ikPath.lastIndexOf("/");
  const body = new FormData();
  body.append("file", new Blob([readFileSync(p.abs)]), p.ikPath.slice(slash + 1));
  body.append("fileName", p.ikPath.slice(slash + 1));
  body.append("folder", `/${p.ikPath.slice(0, slash)}`);
  body.append("useUniqueFileName", "false");
  body.append("publicKey", publicKey);
  body.append("tags", IK_TAG);
  const res = await fetch("https://upload.imagekit.io/api/v1/files/upload", {
    method: "POST",
    headers: { Authorization: auth },
    body,
  });
  const data = (await res.json().catch(() => ({}))) as { filePath?: string; message?: string };
  if (!res.ok || data.filePath?.replace(/^\//, "") !== p.ikPath) {
    throw new Error(
      `Upload of ${p.publicPath} failed (${res.status}): ${data.message ?? JSON.stringify(data)}`,
    );
  }
}

/** Fetch a tiny resized copy of every photo from the CDN — proves the URLs the site will use work. */
async function verifyOnCdn(endpoint: string, photos: Photo[]) {
  const bad: string[] = [];
  await Promise.all(
    photos.map(async (p) => {
      const res = await fetch(`${endpoint}/${p.ikPath}?tr=w-32,q-50,c-at_max`);
      if (!res.ok || !(res.headers.get("content-type") ?? "").startsWith("image/")) {
        bad.push(`${p.publicPath} → ${res.status}`);
      }
    }),
  );
  if (bad.length) throw new Error(`Not served by ImageKit yet:\n  ${bad.join("\n  ")}`);
}

async function sync() {
  const seedEnv = process.env.SEED_ENV === "production" ? "production" : "development";
  config({ path: resolve(webRoot, `.env.${seedEnv}.local`), quiet: true });
  config({ path: resolve(webRoot, `.env.${seedEnv}`), quiet: true });

  const privateKey = process.env.IMAGEKIT_PRIVATE_KEY?.trim();
  const publicKey = process.env.NEXT_PUBLIC_IMAGEKIT_PUBLIC_KEY?.trim();
  const endpoint = process.env.NEXT_PUBLIC_IMAGEKIT_URL_ENDPOINT?.trim().replace(/\/+$/, "");
  if (!privateKey || !publicKey || !endpoint) {
    throw new Error(
      `ImageKit keys missing in .env.${seedEnv}.local (IMAGEKIT_PRIVATE_KEY, NEXT_PUBLIC_IMAGEKIT_PUBLIC_KEY, NEXT_PUBLIC_IMAGEKIT_URL_ENDPOINT).`,
    );
  }
  const auth = `Basic ${Buffer.from(`${privateKey}:`).toString("base64")}`;

  const { photos, files, version } = collect();
  console.log(`${seedEnv}: ${photos.length} bundled photos → ${endpoint}/${IK_ROOT}`);

  const existing = await listExisting(auth);
  const missing = photos.filter((p) => !existing.has(p.ikPath));
  console.log(`  already there: ${photos.length - missing.length}, to upload: ${missing.length}`);
  for (const [i, p] of missing.entries()) {
    await upload(auth, publicKey, p);
    console.log(`  ↑ ${i + 1}/${missing.length} ${p.publicPath}`);
  }

  await verifyOnCdn(endpoint, photos);
  console.log(`  ✓ all ${photos.length} served by ImageKit`);

  const prev = readManifest();
  const manifest: Manifest = {
    _about: ABOUT,
    version,
    files,
    endpoints: { ...(prev?.endpoints ?? {}), [endpoint]: version },
  };
  writeFileSync(MANIFEST_PATH, `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(`  ✓ wrote ${relative(webRoot, MANIFEST_PATH)} (version ${version})`);
  console.log("  Commit that file, then deploy — the site will load these photos from ImageKit.");
}

if (process.argv.includes("--check")) {
  check();
} else {
  sync().catch((e) => {
    console.error(e instanceof Error ? e.message : e);
    process.exit(1);
  });
}
